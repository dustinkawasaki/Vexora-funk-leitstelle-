-- Atomare Leitstellen-Uebernahme: nur ein aktiver RP-Leitstellenplatz.
create or replace function public.vx_claim_dispatcher(p_session_id text, p_display_name text default 'VEXORA RP Leitstelle')
returns boolean
language plpgsql
security definer
set search_path = public
as $$
declare
  current_session text;
  current_expiry timestamptz;
begin
  perform pg_advisory_xact_lock(73482109);
  select session_id, expires_at into current_session, current_expiry
    from public.vx_dispatcher where id = 'main' for update;

  if current_session is not null and current_expiry > now() and current_session <> p_session_id then
    return false;
  end if;

  insert into public.vx_dispatcher(id, session_id, display_name, expires_at)
  values ('main', p_session_id, p_display_name, now() + interval '30 seconds')
  on conflict (id) do update
    set session_id = excluded.session_id,
        display_name = excluded.display_name,
        expires_at = excluded.expires_at;
  return true;
end;
$$;

create or replace function public.vx_renew_dispatcher(p_session_id text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  update public.vx_dispatcher
    set expires_at = now() + interval '30 seconds'
    where id = 'main' and session_id = p_session_id and expires_at > now();
  return found;
end;
$$;

create or replace function public.vx_release_dispatcher(p_session_id text)
returns boolean
language plpgsql
security definer
set search_path = public
as $$
begin
  delete from public.vx_dispatcher where id = 'main' and session_id = p_session_id;
  return found;
end;
$$;

revoke all on function public.vx_claim_dispatcher(text, text) from public;
revoke all on function public.vx_renew_dispatcher(text) from public;
revoke all on function public.vx_release_dispatcher(text) from public;
