-- VEXORA RP Funk-Leitstelle: Supabase Free schema
-- Nur fuer das Roblox-Rollenspiel. Kein echtes Notruf- oder Einsatzsystem.

create table if not exists public.vx_units (
  name text primary key,
  department text not null default 'Unbekannt',
  status text not null default '2 – Einsatzbereit',
  updated_at timestamptz not null default now()
);

create table if not exists public.vx_incidents (
  id bigint generated by default as identity primary key,
  number text not null unique,
  type text not null,
  caller text not null,
  address text not null default 'Nicht angegeben',
  department text not null default 'Unbekannt',
  priority text not null default 'Normal',
  status text not null default 'Offen',
  created_at timestamptz not null default now()
);

create table if not exists public.vx_radio_messages (
  id bigint generated by default as identity primary key,
  kind text not null,
  payload jsonb not null default '{}'::jsonb,
  created_at timestamptz not null default now()
);

create table if not exists public.vx_dispatcher (
  id text primary key check (id = 'main'),
  session_id text not null,
  display_name text not null default 'VEXORA RP Leitstelle',
  expires_at timestamptz not null
);

